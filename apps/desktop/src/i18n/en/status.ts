/** As in `es/status.ts`: a `null` note is not stored. */
const stage = (title: string, note: string | null): ProgressText => (note === null ? { stage: title } : { stage: title, note });

/** An address inside a sentence: "Unnamed alias" (`mail.unnamedAddress`, which stands alone in the sidebar and the row)
 *  goes lowercase mid-sentence ("See mail for unnamed alias"). A real address does not start like that (it has no
 *  spaces). */
const inSentence = (address: string): string => `${address}`.replace(/^Unnamed (mailbox|alias)$/, 'unnamed $1');

