#!/usr/bin/env python3
"""Builds icons.ts and preview.html (local, not tracked) from the SVG files of the NightMail icon set.

The SVG files are the source: one hand-written file per icon, all sharing the same root element. This script
checks that they follow the rules of the set and writes the two generated files next to them.

    python3 tools/build.py
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VIEW_BOX = '0 0 16 16'
# Every icon is drawn with these stroke settings. Filled details opt out on their own element.
STROKE = 'fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"'
HEAD = f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="{VIEW_BOX}" {STROKE}>'
ALLOWED_TAGS = {'path', 'circle', 'rect'}
SIZES = (48, 20, 16)


def read_icon(path):
    text = path.read_text(encoding='utf-8').strip()
    if not text.startswith(HEAD) or not text.endswith('</svg>'):
        sys.exit(f'{path.name}: the root element must be exactly\n  {HEAD}')
    body = ''.join(line.strip() for line in text[len(HEAD):-len('</svg>')].splitlines())
    tags = set(re.findall(r'<([a-zA-Z]+)', body))
    if not tags or tags - ALLOWED_TAGS:
        sys.exit(f'{path.name}: only {sorted(ALLOWED_TAGS)} are allowed, found {sorted(tags)}')
    colours = set(re.findall(r'(?:fill|stroke)="([^"]+)"', body)) - {'currentColor', 'none'}
    if colours:
        sys.exit(f'{path.name}: colours must be currentColor or none, found {sorted(colours)}')
    if "'" in body or '\\' in body:
        sys.exit(f'{path.name}: quotes and backslashes are not allowed in the markup')
    return body


def write_ts(icons):
    lines = [
        '// NightMail icon set. Generated by tools/build.py from the SVG files in this folder: do not edit by hand.',
        '//',
        '// `body` is the inner markup of an <svg> element with the given `viewBox`. It carries its own stroke and',
        '// fill settings and takes its colour from `currentColor`, so it does not depend on any outside style.',
        '',
        'export interface IconDef {',
        '  readonly viewBox: string;',
        '  readonly body: string;',
        '}',
        '',
        'export const ICONS = {',
    ]
    for name, body in icons.items():
        lines.append(f"  '{name}': {{")
        lines.append(f"    viewBox: '{VIEW_BOX}',")
        lines.append(f"    body: '<g {STROKE}>{body}</g>',")
        lines.append('  },')
    lines += ['} as const satisfies Record<string, IconDef>;', '', 'export type IconName = keyof typeof ICONS;', '']
    (ROOT / 'icons.ts').write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def svg(name, body, size):
    spin = ' class="spin"' if name == 'espera' else ''
    return (f'<svg{spin} width="{size}" height="{size}" viewBox="{VIEW_BOX}" aria-hidden="true">'
            f'<g {STROKE}>{body}</g></svg>')


def write_preview(icons):
    cards = []
    for name, body in icons.items():
        sizes = ''.join(f'<span class="size">{svg(name, body, s)}<small>{s}</small></span>' for s in SIZES)
        cards.append(f'<figure><div class="sizes">{sizes}</div><figcaption>{html.escape(name)}</figcaption></figure>')
    grid = '\n      '.join(cards)
    page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>NightMail icons</title>
<style>
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; font: 14px/20px Figtree, "Segoe UI", system-ui, sans-serif; background: #e9e2d0; color: #0a1828; }}
  header {{ padding: 24px 32px 8px; }}
  h1 {{ margin: 0 0 4px; font-size: 20px; line-height: 28px; }}
  header p {{ margin: 0; color: #45546a; }}
  section {{ margin: 16px 32px; padding: 20px 24px 24px; border-radius: 10px; }}
  section h2 {{ margin: 0 0 16px; font-size: 14px; font-weight: 600; }}
  .light {{ background: #ffffff; color: #0a1828; --weak: #5a687b; --line: #e9e2d0; }}
  .dark {{ background: #0a1828; color: #f5f0e4; --weak: #8496ab; --line: #1e3650; }}
  .grid {{ display: grid; grid-template-columns: repeat(auto-fill, minmax(176px, 1fr)); gap: 12px; }}
  figure {{ margin: 0; padding: 14px 12px 10px; border: 1px solid var(--line); border-radius: 10px; }}
  .sizes {{ display: flex; align-items: flex-end; justify-content: center; gap: 20px; }}
  .size {{ display: flex; flex-direction: column; align-items: center; gap: 6px; }}
  .size small {{ color: var(--weak); font-size: 11px; line-height: 12px; }}
  svg {{ display: block; }}
  figcaption {{ margin-top: 10px; text-align: center; color: var(--weak);
               font: 12px/16px "Atkinson Hyperlegible Mono", Consolas, ui-monospace, monospace; }}
  .spin {{ animation: spin 1s linear infinite; }}
  @keyframes spin {{ to {{ transform: rotate(360deg); }} }}
</style>
</head>
<body>
  <header>
    <h1>NightMail icons</h1>
    <p>{len(icons)} icons on a 16 px grid, 1.5 px stroke, shown at 48, 20 and 16 px. Colour is inherited from the text.</p>
  </header>
  <section class="light">
    <h2>Light</h2>
    <div class="grid">
      {grid}
    </div>
  </section>
  <section class="dark">
    <h2>Dark</h2>
    <div class="grid">
      {grid}
    </div>
  </section>
</body>
</html>
'''
    (ROOT / 'preview.html').write_text(page, encoding='utf-8', newline='\n')


def main():
    icons = {path.stem: read_icon(path) for path in sorted(ROOT.glob('*.svg'))}
    if not icons:
        sys.exit('no SVG files found')
    write_ts(icons)
    write_preview(icons)
    print(f'{len(icons)} icons -> icons.ts, preview.html')


if __name__ == '__main__':
    main()
